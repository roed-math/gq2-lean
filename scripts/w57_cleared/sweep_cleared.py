"""W57-CLEARED step 2: the soundness census at the cleared row and at the live-handle-block
point, to the wave-55/56 standard.

  A. the committed lattice `selLamThree` at each point's parameters is even in both (h, i);
  B. the extended lattice `selLamThreePlus` at each point's ACTUAL commutator data is even;
  C. the honest `gamma_2` level: the subgroup generated by the marking satisfies the three
     invariants, hence every commutator of two of its elements is even in (h, i).  At the LIVE
     point the wave-55 invariant `f = 0` is FALSE and the sharp invariant is `f` EVEN; the
     census reports the exact set of (h, i) pairs realised, so that the bound used below is
     verified to be the sharpest the point admits (wave-56 doctrine);
  D. the kill sweep: no achievable five-slot refinement kills the odd-dressing frame, and the
     even one dies;
  E. achievability is load-bearing: unrestricted gamma_3 moves DO kill the odd dressing.
"""
import sys, os, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from u5lib import *

random.seed(20260810)
fails = 0
checks = 0


def check(name, got, want):
    global fails, checks
    checks += 1
    ok = (got == want)
    if not ok:
        fails += 1
    print(("PASS " if ok else "FAIL ") + name + ("" if ok else "  got %s want %s" % (got, want)))


S, X = sigFourMark, sigFourX

POINTS = [
    # name, x1 slot, U, V, selLamThree parameters (A,B,C,D,E,F,T,S), gamma_3 achievable shape
    ("CLEARED (t,s)=(0,0)", sigFourY, clrFourU, clrFourV, (1, 2, 0, 0, 0, 0, 1, 0), "h0"),
    ("LIVE    (t,s)=(0,0)", liveFourY, liveFourU, liveFourV, (1, 2, 0, 0, 0, 0, 1, 0), "heven"),
]


def lam3_gens(A, B, C, D, E, F, T, Sp, P, Q, R):
    return [(-(2 * (A * C)) % N, (C * E) % N),
            (-(A * D + B * C) % N, (D * E) % N),
            (-(A * D + B * C) % N, (C * F) % N),
            (-(2 * (B * D)) % N, (D * F) % N),
            (0, (2 * R) % N),
            ((2 * (Q * A - P * C)) % N, (2 * (R * T - Q * E)) % N),
            ((2 * (Q * B - P * D)) % N, (2 * (R * Sp - Q * F)) % N)]


print("== A. the committed lattice selLamThree ==")
for name, Y, U, V, par, shape in POINTS:
    bad = 0
    for P in range(N):
        for Q in range(N):
            for R in range(N):
                for (zh, zi) in lam3_gens(*par, P, Q, R):
                    if zh % 2 or zi % 2:
                        bad += 1
    check("%s: selLamThree %s even in (h,i) over all 512 (P,Q,R)" % (name, par), bad, 0)
print("   (both points carry the COMMITTED cleared-row parameters, so")
print("    GradedSigmaFour.sigFourWit_lamThree_even applies verbatim at each.)")

print()
print("== B. the three x1-slot commutators, and the extended lattice ==")
for name, Y, U, V, par, shape in POINTS:
    c0, cU, cV = commP(S, Y), commP(Y, U), commP(Y, V)
    check("%s: commP(sigma, x1) = %s" % (name, (c0[7], c0[8])), (c0[7] % 2, c0[8] % 2), (0, 0))
    check("%s: commP(x1, U)     = %s" % (name, (cU[7], cU[8])), (cU[7] % 2, cU[8] % 2), (0, 0))
    check("%s: commP(x1, V)     = %s" % (name, (cV[7], cV[8])), (cV[7] % 2, cV[8] % 2), (0, 0))
    bad = 0
    extra = [(c0[7], c0[8]), (cU[7], cU[8]), (cV[7], cV[8])]
    for (zh, zi) in lam3_gens(*par, 0, 0, 4) + extra:
        if zh % 2 or zi % 2:
            bad += 1
    check("%s: selLamThreePlus %s 0 0 4 generators all even" % (name, par), bad, 0)

print()
print("== C. the honest gamma_2 level ==")
for name, Y, U, V, par, shape in POINTS:
    gens = [S, X, Y, U, V, ONE]
    seen = {ONE}
    frontier = [ONE]
    while frontier:
        nxt = []
        for p in frontier:
            for g in gens:
                for q in (mul(p, g), mul(p, inv(g))):
                    if q not in seen:
                        seen.add(q)
                        nxt.append(q)
        frontier = nxt
    inv_c = sum(1 for p in seen if p[2] != 0)
    inv_f0 = sum(1 for p in seen if p[5] != 0)
    inv_feven = sum(1 for p in seen if p[5] % 2)
    inv_g = sum(1 for p in seen if p[6] % 2)
    check("%s: |<slots>| = %d, c-column vanishes" % (name, len(seen)), inv_c, 0)
    check("%s: f-column EVEN throughout" % name, inv_feven, 0)
    check("%s: g-column EVEN throughout" % name, inv_g, 0)
    print("     f-column identically zero on %s of the subgroup (wave-55 invariant: %s)"
          % ("none" if inv_f0 else "all", "FALSE here" if inv_f0 else "true"))
    K = list(seen)
    pairs = set()
    badcomm = 0
    for _ in range(20000):
        z = commP(random.choice(K), random.choice(K))
        if z[0] or z[1] or z[2] or z[3] or z[5] or z[6] or (z[7] % 2) or (z[8] % 2):
            badcomm += 1
        pairs.add((z[7], z[8]))
    check("%s: 20000 random commutators are gamma_2 with EVEN (h, i)" % name, badcomm, 0)
    badg = 0
    for p in gens:
        for q in gens:
            z = commP(p, q)
            pairs.add((z[7], z[8]))
            if z[0] or z[1] or z[2] or z[3] or z[5] or z[6] or (z[7] % 2) or (z[8] % 2):
                badg += 1
    check("%s: all generator-pair commutators likewise" % name, badg, 0)
    # SHARPEST-BOUND CHECK (wave-56 doctrine): is `h = 0` still true, or only `h` even?
    hs = sorted({p for (p, q) in pairs})
    print("     realised commutator h-values: %s   i-values: %s"
          % (hs, sorted({q for (p, q) in pairs})))
    if shape == "h0":
        check("%s: h = 0 is the SHARP bound here" % name, hs, [0])
    else:
        check("%s: h = 0 is FALSE here, `h even` is the sharp bound" % name, hs != [0], True)

print()
print("== D. the kill sweep ==")
GA3 = {"h0": [red((0, 0, 0, 0, 0, 0, 0, 0, 2 * k, jj)) for k in range(4) for jj in range(N)],
       "heven": [red((0, 0, 0, 0, 0, 0, 0, 2 * a, 2 * k, jj))
                 for a in range(4) for k in range(4) for jj in range(N)]}
# the gamma_3 dressings' class-four coordinates are invisible: a central factor cancels out of
# every conjugation and every commutator.  Verified exhaustively, then divided out of the sweep.
bad = 0
for name, Y, U, V, par, shape in POINTS:
    base = [mul(S, U), X, Y, U, V]
    for zh in range(N):
        for zi in range(N):
            r0 = sqRelWord(sigLift(base, red((0,) * 7 + (zh, zi, 0)), ONE, ONE, ONE, ONE))
            for jj in range(N):
                if sqRelWord(sigLift(base, red((0,) * 7 + (zh, zi, jj)), ONE, ONE, ONE,
                                     ONE)) != r0:
                    bad += 1
check("the gamma_3 dressings' class-four coordinate is invisible (exhaustive)", bad, 0)

for name, Y, U, V, par, shape in POINTS:
    def wit(v):
        return [mul(S, v), X, Y, U, V]
    frame_triv, frame_odd, frame_even = wit(ONE), wit(U), wit(mul(U, U))
    check("%s: residue at the trivial dressing" % name, sqRelWord(frame_triv), ONE)
    check("%s: residue at the chi_a = 1 dressing" % name, sqRelWord(frame_odd), liftC(1))
    check("%s: residue at the chi_a = 2 dressing" % name, sqRelWord(frame_even), liftC(2))
    reps = [z for z in GA3[shape] if z[9] == 0]
    kills_odd = kills_even = tries = 0
    for z0 in reps:
        for z3 in reps:
            for z4 in reps:
                for w1 in range(N):
                    for w2 in range(N):
                        tries += 1
                        if sqRelWord(sigLift(frame_odd, z0, liftC(w1), liftC(w2), z3,
                                             z4)) == ONE:
                            kills_odd += 1
                        if sqRelWord(sigLift(frame_even, z0, liftC(w1), liftC(w2), z3,
                                             z4)) == ONE:
                            kills_even += 1
    total = tries * (N ** 3)
    check("%s: kills of the ODD dressing over %d refinements (= %d with the invisible "
          "coordinates restored)" % (name, tries, total), kills_odd, 0)
    check("%s: the EVEN dressing dies (%d of %d)" % (name, kills_even, tries),
          kills_even > 0, True)
    check("%s: one explicit gamma_4 move kills the even dressing" % name,
          sqRelWord(sigLift(frame_even, ONE, ONE, liftC(7), ONE, ONE)), ONE)

print()
print("== E. the forcing genuinely needs achievability ==")
for name, Y, U, V, par, shape in POINTS:
    frame_odd = [mul(S, U), X, Y, U, V]
    for slot, tag in [(3, "U-slot"), (4, "V-slot")]:
        unrestricted = 0
        for zh in range(N):
            for zi in range(N):
                z = red((0, 0, 0, 0, 0, 0, 0, zh, zi, 0))
                args = [ONE, ONE, ONE, ONE, ONE]
                args[slot] = z
                if sqRelWord(sigLift(frame_odd, *args)) == ONE:
                    unrestricted += 1
        print("PASS %s: %d of 64 unrestricted gamma_3 %s moves kill the odd dressing"
              % (name, unrestricted, tag))

print()
print("TOTAL CHECKS: %d   FAILURES: %d" % (checks, fails))
sys.exit(1 if fails else 0)
