"""W58-TWOLIVE: exhaustive kill sweeps and subgroup censuses at every new point.

For each point we build the subgroup `K` generated by the marking's slots, then its derived
subgroup `[K, K]` - the `rowGaTwoOf` of the Lean file, i.e. the set the achievability
convention lets a `gamma_2`-level dressing be drawn from - intersect with `gamma_3` to get the
ACHIEVABLE handle dressings `A`, and sweep every five-slot class-four refinement
`(z0, w1, w2, z3, z4)` in `gamma_3 x gamma_4 x gamma_4 x A x A`.

The sweep is exact: the five-slot translation identity reads only the eight coordinates
`(z0.h, z0.i, w1.j, w2.j, z3.h, z3.i, z4.h, z4.i)`, so the refinements are grouped by those
and counted with multiplicity.  A brute-force cross-check on a subsample confirms the grouping.

Run:  python3 scripts/w58_twolive/sweep_twolive.py

BRACKET CONVENTION.  [PAPER]
This script computes brackets in the paper convention, and its Lean target is written
with commP, the same convention.
Paper convention: commP x y = x^-1 y^-1 x y (GQ2/Words.lean:59, and every python commP
in scripts/).  Mathlib convention: [x, y] = x y x^-1 y^-1.  They are DIFFERENT families,
[x, y]_mathlib = commP x^-1 y^-1 (GradedFiveForce.commutatorElement_eq_commP), so a
paper-convention computation certifies a commP-written Lean statement and MIS-certifies a
[.,.]-written one.  Normal-closure and subgroup sifts are convention-IMMUNE.
"""
