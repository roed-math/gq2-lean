def closure(gens):
    S = {ONE}
    frontier = [ONE]
    gs = list(gens) + [inv(g) for g in gens]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gs:
                y = mul(x, g)
                if y not in S:
                    S.add(y)
                    nxt.append(y)
        frontier = nxt
    return S


def derived(gens):
    """[K, K] for K = <gens>: the normal closure in K of the generator commutators, built by
    sifting - a new element is added to the (small) generating list only when it is not yet in
    the subgroup, so the closure is never run on a large generating set."""
    gs = [g for g in gens if g != ONE]
    state = {"D": {ONE}, "gl": []}

    def add(z):
        if z not in state["D"]:
            state["gl"].append(z)
            state["D"] = closure(state["gl"])

    for p in gs:
        for q in gs:
            add(commP(p, q))
    changed = True
    while changed:
        changed = False
        for z in list(state["D"]):
            for g in gs:
                w = commP(z, g)
                if w not in state["D"]:
                    add(w)
                    changed = True
    return state["D"]


def comm_values(gens, K, samples=20000):
    """The commutator values realised: all generator pairs, plus a random sample from K."""
    vals = {commP(p, q) for p in gens for q in gens}
    Kl = list(K)
    for _ in range(samples):
        vals.add(commP(random.choice(Kl), random.choice(Kl)))
    return vals


def hi_multiset(S):
    return Counter((z[7], z[8]) for z in S)


GA3_HI = Counter()
for a in R8:
    for b in R8:
        GA3_HI[(a, b)] = 8          # the free class-four coordinate


def kill_count(base, m, j, A):
    """Exact number of refinements (z0, w1, w2, z3, z4) in gamma_3 x gamma_4^2 x A^2 whose
    translation kills `base`, plus the total swept."""
    x, U, V = m[1], m[3 + 2 * j], m[4 + 2 * j]
    Ahi = hi_multiset(A)
    total = 0
    killed = 0
    for (z0h, z0i), n0 in GA3_HI.items():
        t0 = (z0h * x[3] - z0i * x[0]) % 8
        for w1j in R8:
            for w2j in R8:
                t1 = (t0 - 4 * w1j + 2 * w2j) % 8
                for (z3h, z3i), n3 in Ahi.items():
                    t2 = (t1 + z3h * V[3] - z3i * V[0]) % 8
                    for (z4h, z4i), n4 in Ahi.items():
                        inc = (t2 + U[0] * z4i - U[3] * z4h) % 8
                        w = n0 * n3 * n4
                        total += w
                        if mul(base, liftC(inc)) == ONE:
                            killed += w
    return killed, total


def brute_check(base, m, j, A, trials=40000):
    """Independent random cross-check of `kill_count` on individual refinements."""
    GA3 = [(0, 0, 0, 0, 0, 0, 0, a, b, c) for a in R8 for b in R8 for c in R8]
    x, U, V = m[1], m[3 + 2 * j], m[4 + 2 * j]
    hits = 0
    for _ in range(trials):
        z0 = random.choice(GA3)
        w1 = liftC(random.randrange(8))
        w2 = liftC(random.randrange(8))
        z3 = random.choice(A)
        z4 = random.choice(A)
        inc = ((z0[7] * x[3] - z0[8] * x[0]) + (-4 * w1[9] + 2 * w2[9])
               + (z3[7] * V[3] - z3[8] * V[0]) + (U[0] * z4[8] - U[3] * z4[7])) % 8
        if mul(base, liftC(inc)) == ONE:
            hits += 1
    return hits, trials


def sweep(name, mark, wit_odd, wit_even, j):
    gens = [p for p in mark]
    K = closure(gens)
    D = derived(gens)
    A = [z for z in D if is_ga_three(z)]
    cv = comm_values(gens, K)
    print("\n--- %s" % name)
    print("    |<slots>| = %d ;  |[K,K]| = %d ;  achievable gamma_3 dressings = %d"
          % (len(K), len(D), len(A)))
    print("    commutator h-values realised: %s ;  i-values: %s"
          % (sorted({z[7] for z in cv}), sorted({z[8] for z in cv})))
    check("%s: [K,K] is EVEN in both class-three coordinates" % name,
          all(z[7] % 2 == 0 and z[8] % 2 == 0 for z in D))
    check("%s: the sharper W55 bound (first class-three coordinate = 0) is REFUTED" % name,
          any(z[7] != 0 for z in D))
    ko, tot = kill_count(sqRelWord(wit_odd), wit_odd, j, A)
    ke, _ = kill_count(sqRelWord(wit_even), wit_even, j, A)
    print("    refinements swept: %d ;  kill the ODD dressing: %d ;  the EVEN one: %d"
          % (tot, ko, ke))
    hits, trials = brute_check(sqRelWord(wit_odd), wit_odd, j, A)
    check("%s: brute-force cross-check agrees that none kills the odd dressing" % name,
          (hits == 0) == (ko == 0))
    check("%s: NO achievable refinement kills the odd dressing" % name, ko == 0)
    check("%s: some achievable refinement kills the even dressing" % name, ke > 0)
    GA3 = [(0, 0, 0, 0, 0, 0, 0, a, b, c) for a in R8 for b in R8 for c in R8]
    unres, untot = kill_count(sqRelWord(wit_odd), wit_odd, j, GA3)
    print("    with UNRESTRICTED gamma_3 handle moves: %d of %d kill it" % (unres, untot))
    check("%s: achievability is load-bearing (unrestricted moves DO kill it)" % name,
          unres > 0)


