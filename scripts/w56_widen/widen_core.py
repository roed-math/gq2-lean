"""W56-WIDEN, part 1: the mod-2 core.

Question.  `GradedObstructionPlus.sqRelWord_selLamTwo_ne_one` quantifies over `selLamTwo`,
whose `(h, i)`-data are constrained to `selLamThreePlus`.  The honest achievable object is
`gamma2(im Phi) = <[K, K], x1^2>` with `K = <the five witness frame slots>`, whose
`(h, i)`-data are NOT known to lie in `selLamThreePlus`.  Does the obstruction still hold
over the honest object, and with which hypotheses?

Everything the obstruction reads is a parity, so the whole question lives mod 2.  This script
answers it exhaustively:

  A. the mod-2 subgroup `Kbar <= U5(F2)/gamma3` generated by the five reduced slots, at every
     one of the 4096 mod-2 parameter points, filtered by (four parity rows, fourteen pairings
     even, class-four selection bit odd);
  B. for every ORDERED PAIR (p, q) of elements of `Kbar`, the three parities the obstruction
     consumes:  the commutator's `g`-column, and its two `(h, i)`-pairings against the `V`-
     and `U`-letters' outer columns `(F, B)` and `(E, A)`;
  C. the six facts the Lean proof consumes -- `A` even, `B` even, and `P*C*E`, `P*C*F`,
     `P*D*E`, `P*D*F` even -- each checked to follow from the same filter (this is the
     `ZMod 2` `decide` core that gets transcribed as `widenAb_core`);
  D. the shape predicate `selFrameW` that the Lean closure induction will carry, checked to
     contain `Kbar` at every point.

No external packages.  Run:  python3 scripts/w56_widen/widen_core.py
"""

import itertools
import sys

VARS = "A B C D E F T S P Q R W2".split()


# --------------------------------------------------------------------------------------
# the mod-2 frame: the five nontrivial slots of `selLiftWit`, reduced.
# GradedLift.selLiftWit:
#   slot0 sigma = (0, 1, 0, 0, 0, 0, 0, ...)
#   slot1 x0    = (B*T - A*S, 0, D*T - C*S, F*T - E*S, -2*T*S*B, S*T*C + T*S*D, 0, ...)
#   slot2 x1    = (0, 0, 0, 0, P, Q, R, -(A+B)*Q, 0, 0)
#   slotU       = (A, 0, C, E, 0, -(T*C), 0, ...)
#   slotV       = (B, 0, D, F, -(B*S), 0, 0, ...)
# --------------------------------------------------------------------------------------

def slots_mod2(v):
    A, B, C, D, E, F, T, S, P, Q, R, W2 = v
    sigma = (0, 1, 0, 0, 0, 0, 0)
    x0 = ((B * T + A * S) % 2, 0, (D * T + C * S) % 2, (F * T + E * S) % 2,
          0, (S * T * C + T * S * D) % 2, 0)
    x1 = (0, 0, 0, 0, P, Q, R)
    U = (A, 0, C, E, 0, (T * C) % 2, 0)
    V = (B, 0, D, F, (B * S) % 2, 0, 0)
    return [sigma, x0, x1, U, V]


def mul7(p, q):
    """(a,b,c,d,e,f,g) multiplication of U5 mod 2 (the quotient U5/gamma3)."""
    pa, pb, pc, pd, pe, pf, pg = p
    qa, qb, qc, qd, qe, qf, qg = q
    return ((pa + qa) % 2, (pb + qb) % 2, (pc + qc) % 2, (pd + qd) % 2,
            (pe + qe + pa * qb) % 2, (pf + qf + pb * qc) % 2, (pg + qg + pc * qd) % 2)


def inv7(p):
    pa, pb, pc, pd, pe, pf, pg = p
    return ((-pa) % 2, (-pb) % 2, (-pc) % 2, (-pd) % 2,
            (pa * pb - pe) % 2, (pb * pc - pf) % 2, (pc * pd - pg) % 2)


def subgroup7(gens):
    ident = (0,) * 7
    seen = {ident}
    frontier = [ident]
    gg = list(gens) + [inv7(g) for g in gens]
    while frontier:
        nxt = []
        for x in frontier:
            for g in gg:
                y = mul7(x, g)
                if y not in seen:
                    seen.add(y)
                    nxt.append(y)
        frontier = nxt
    return sorted(seen)


def comm3L(p, q):
    """u5Comm3L, the `h`-coordinate of [p, q] (GradedFour.lean)."""
    pa, pb, pc, pd, pe, pf, pg = p
    qa, qb, qc, qd, qe, qf, qg = q
    return (pa * qf - pf * qa + pe * qc - pc * qe
            + pa * pc * qb - pa * pb * qc + pc * qa * qb - pb * qa * qc) % 2


def comm3R(p, q):
    """u5Comm3R, the `i`-coordinate of [p, q]."""
    pa, pb, pc, pd, pe, pf, pg = p
    qa, qb, qc, qd, qe, qf, qg = q
    return (pb * qg - pg * qb + pf * qd - pd * qf
            + pb * pd * qc - pb * pc * qd + pd * qb * qc - pc * qb * qd) % 2


def commG(p, q):
    return (p[2] * q[3] - p[3] * q[2]) % 2


# --------------------------------------------------------------------------------------
# the filter: parity rows, the fourteen pairings, the class-four selection bit
# --------------------------------------------------------------------------------------

def rows_mod2(v):
    A, B, C, D, E, F, T, S, P, Q, R, W2 = v
    return [(A * S + B * T) % 2,        # hd : 2P + (A*S - B*T) = 0
            (D * T + C * S) % 2,        # he : 2Q + (T*D - S*C) = 0
            (C * F + D * E) % 2,        # hg : 2R + (C*F - D*E) = 0
            (E * S + F * T) % 2]        # hb : 2W2 + (E*S - F*T) = 0


def pairings14_mod2(v):
    """The fourteen hypotheses of `sqRelWord_selLamTwo_ne_one`, reduced mod 2."""
    A, B, C, D, E, F, T, S, P, Q, R, W2 = v
    h1 = (2 * (A * C) * F + (C * E) * B) % 2
    h2 = ((A * D + B * C) * F + (D * E) * B) % 2
    h3 = ((A * D + B * C) * F + (C * F) * B) % 2
    h4 = (2 * (B * D) * F + (D * F) * B) % 2
    h5 = (R * B) % 2
    h6 = ((P * C - Q * A) * F - (Q * E) * B) % 2
    h7 = ((P * D - Q * B) * F - (Q * F) * B) % 2
    h1p = (A * (C * E) + E * (2 * (A * C))) % 2
    h2p = (A * (D * E) + E * (A * D + B * C)) % 2
    h3p = (A * (C * F) + E * (A * D + B * C)) % 2
    h4p = (A * (D * F) + E * (2 * (B * D))) % 2
    h5p = (A * R) % 2
    h6p = (A * (Q * E) - E * (P * C - Q * A)) % 2
    h7p = (A * (Q * F) - E * (P * D - Q * B)) % 2
    return [h1, h2, h3, h4, h5, h6, h7, h1p, h2p, h3p, h4p, h5p, h6p, h7p]


def bit_mod2(v):
    """selLiftWit_bit: (A*(C*F) + B*(D*E))*T + P*R."""
    A, B, C, D, E, F, T, S, P, Q, R, W2 = v
    return ((A * (C * F) + B * (D * E)) * T + P * R) % 2


def live(v):
    return all(x == 0 for x in rows_mod2(v)) and \
        all(x == 0 for x in pairings14_mod2(v)) and bit_mod2(v) == 1


# --------------------------------------------------------------------------------------
# C. the six facts the Lean core produces
# --------------------------------------------------------------------------------------

def monomials(v):
    """The six facts the Lean `ZMod 2` core has to produce, and nothing else."""
    A, B, C, D, E, F, T, S, P, Q, R, W2 = v
    return {
        "A": A % 2,
        "B": B % 2,
        "P*C*E": (P * C * E) % 2,
        "P*C*F": (P * C * F) % 2,
        "P*D*E": (P * D * E) % 2,
        "P*D*F": (P * D * F) % 2,
    }


# --------------------------------------------------------------------------------------
# D. the shape predicate the Lean closure induction carries
# --------------------------------------------------------------------------------------

def shape_set(v):
    """All (a,b,c,d,e,f,g) mod 2 allowed by the Lean predicate `selFrameW`:

        a even,   c = al*C + be*D,   d = al*E + be*F  (one shared (al, be)),
        e = ep*P,
        b, f, g arbitrary.
    """
    A, B, C, D, E, F, T, S, P, Q, R, W2 = v
    out = set()
    for al, be in itertools.product((0, 1), repeat=2):
        c = (al * C + be * D) % 2
        d = (al * E + be * F) % 2
        for ep in (0, 1):
            e = (ep * P) % 2
            for b in (0, 1):
                for f in (0, 1):
                    for g in (0, 1):
                        out.add((0, b, c, d, e, f, g))
    return out


def main():
    pts = list(itertools.product((0, 1), repeat=12))
    livepts = [v for v in pts if live(v)]

    out = []
    w = out.append
    w("W56-WIDEN part 1: the mod-2 core")
    w("=" * 78)
    w("")
    w("mod-2 parameter points (A,B,C,D,E,F,T,S,P,Q,R,W2) : %d" % len(pts))
    w("  ... satisfying the four parity rows              : %d"
      % sum(1 for v in pts if all(x == 0 for x in rows_mod2(v))))
    w("  ... and the fourteen pairings even               : %d"
      % sum(1 for v in pts if all(x == 0 for x in rows_mod2(v))
            and all(x == 0 for x in pairings14_mod2(v))))
    w("  ... and the class-four selection bit ODD  (LIVE) : %d" % len(livepts))
    w("")

    # ---- C : the fifteen monomial facts ------------------------------------------
    w("C. the six facts the Lean ZMod 2 core produces, on the LIVE set")
    w("-" * 78)
    bad_mono = {}
    for v in livepts:
        for k, val in monomials(v).items():
            if val != 0:
                bad_mono.setdefault(k, []).append(v)
    for k in monomials(pts[0]):
        n = len(bad_mono.get(k, []))
        w("  %-12s even at all live points : %s" % (k, "YES" if n == 0 else "NO (%d)" % n))
    w("")
    w("  => monomial mismatches: %d" % sum(len(x) for x in bad_mono.values()))
    w("")

    # ---- B : the exhaustive subgroup check ---------------------------------------
    w("B. the honest object: Kbar = <five reduced slots> <= U5(F2)/gamma3,")
    w("   and every ORDERED PAIR of its elements")
    w("-" * 78)
    sizes = {}
    bad_g = bad_U = bad_V = 0
    tot_pairs = 0
    for v in livepts:
        K = subgroup7(slots_mod2(v))
        sizes[len(K)] = sizes.get(len(K), 0) + 1
        A, B, C, D, E, F, T, S, P, Q, R, W2 = v
        for p in K:
            for q in K:
                tot_pairs += 1
                L = comm3L(p, q)
                Rr = comm3R(p, q)
                if commG(p, q) != 0:
                    bad_g += 1
                if (L * F + Rr * B) % 2 != 0:
                    bad_U += 1
                if (L * E + Rr * A) % 2 != 0:
                    bad_V += 1
    w("  |Kbar| distribution over live points : %s"
      % ", ".join("%d:%d" % (k, sizes[k]) for k in sorted(sizes)))
    w("  ordered pairs tested                 : %d" % tot_pairs)
    w("  commutator g-column odd              : %d" % bad_g)
    w("  U-slot pairing  h*F - i*B  odd       : %d" % bad_U)
    w("  V-slot pairing  h*E - i*A  odd       : %d" % bad_V)
    w("")

    # ---- D : the shape predicate --------------------------------------------------
    w("D. the Lean shape predicate `selFrameW` contains Kbar")
    w("-" * 78)
    bad_shape = 0
    bad_shape_all = 0
    for v in pts:
        if not all(x == 0 for x in rows_mod2(v)):
            continue
        K = subgroup7(slots_mod2(v))
        S_ = shape_set(v)
        for p in K:
            if p not in S_:
                bad_shape_all += 1
                if live(v):
                    bad_shape += 1
    w("  elements of Kbar outside the shape set, live points : %d" % bad_shape)
    w("  ... over ALL points satisfying the four rows        : %d  (expected nonzero:" %
      bad_shape_all)
    w("      the shape's `a` column is even only because A and B are, which is a")
    w("      consequence of the hypotheses, not of the parity rows)")
    w("")

    # ---- B' : the same three parities for the SHAPE set (what Lean proves) -------
    w("B'. the three parities for every ordered pair from the SHAPE set")
    w("    (this is the statement the Lean commutator lemma proves)")
    w("-" * 78)
    s_bad_g = s_bad_U = s_bad_V = 0
    s_tot = 0
    for v in livepts:
        A, B, C, D, E, F, T, S, P, Q, R, W2 = v
        S_ = sorted(shape_set(v))
        for p in S_:
            for q in S_:
                s_tot += 1
                L = comm3L(p, q)
                Rr = comm3R(p, q)
                if commG(p, q) != 0:
                    s_bad_g += 1
                if (L * F + Rr * B) % 2 != 0:
                    s_bad_U += 1
                if (L * E + Rr * A) % 2 != 0:
                    s_bad_V += 1
    w("  ordered pairs tested           : %d" % s_tot)
    w("  commutator g-column odd        : %d" % s_bad_g)
    w("  U-slot pairing odd             : %d" % s_bad_U)
    w("  V-slot pairing odd             : %d" % s_bad_V)
    w("")

    # ---- E : which hypotheses the six facts actually need -------------------------
    w("E. minimality: which of the fourteen pairings the six facts consume")
    w("-" * 78)
    names14 = ["h1", "h2", "h3", "h4", "h5", "h6", "h7",
               "h1'", "h2'", "h3'", "h4'", "h5'", "h6'", "h7'"]

    def holds(drop):
        """Do the six facts hold on the filter with the pairings in `drop` removed?"""
        for v in pts:
            if not all(x == 0 for x in rows_mod2(v)):
                continue
            p14 = pairings14_mod2(v)
            if any(p14[k] != 0 for k in range(14) if k not in drop):
                continue
            if bit_mod2(v) != 1:
                continue
            if any(x != 0 for x in monomials(v).values()):
                return False
        return True

    needed = []
    for k in range(14):
        if not holds({k}):
            needed.append(names14[k])
    w("  pairings whose removal breaks the six facts : %s" % ", ".join(needed))
    # greedy minimal subset
    keep = set(range(14))
    for k in range(14):
        trial = keep - {k}
        if holds(set(range(14)) - trial):
            keep = trial
    w("  a minimal sufficient subset                 : %s"
      % ", ".join(names14[k] for k in sorted(keep)))
    w("  ... and without the odd class-four bit      : %s"
      % ("still holds" if all(
          not (all(x == 0 for x in rows_mod2(v))
               and all(x == 0 for x in pairings14_mod2(v))
               and any(y != 0 for y in monomials(v).values()))
          for v in pts) else "FAILS (the bit is load-bearing)"))
    w("")

    total = (sum(len(x) for x in bad_mono.values()) + bad_g + bad_U + bad_V
             + bad_shape + s_bad_g + s_bad_U + s_bad_V)
    w("=" * 78)
    w("TOTAL MISMATCHES: %d" % total)
    w("=" * 78)

    text = "\n".join(out)
    print(text)
    with open("scripts/w56_widen/results/widen_core.txt", "w") as fh:
        fh.write(text + "\n")
    return 0 if total == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
