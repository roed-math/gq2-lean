# ---------------------------------------------------------------- words

# A word is a tuple:  ('g', name) | ('mul', w1, w2) | ('inv', w) | ('comm', w1, w2)
# | ('pow', w, n) | ('one',)


def w_eval(w, env):
    t = w[0]
    if t == 'g':
        return env[w[1]]
    if t == 'one':
        return ONE
    if t == 'mul':
        return mul(w_eval(w[1], env), w_eval(w[2], env))
    if t == 'inv':
        return inv(w_eval(w[1], env))
    if t == 'comm':
        return commP(w_eval(w[1], env), w_eval(w[2], env))
    if t == 'pow':
        e = w[2]
        base = w_eval(w[1], env)
        if e < 0:
            base = inv(base)
            e = -e
        return power(base, e)
    raise ValueError(w)


def w_size(w):
    t = w[0]
    if t in ('g', 'one'):
        return 1
    if t in ('mul', 'comm'):
        return 1 + w_size(w[1]) + w_size(w[2])
    if t == 'inv':
        return 1 + w_size(w[1])
    if t == 'pow':
        return 1 + w_size(w[1]) + abs(w[2])
    raise ValueError(w)


def w_str(w):
    t = w[0]
    if t == 'g':
        return w[1]
    if t == 'one':
        return "1"
    if t == 'mul':
        return "(%s * %s)" % (w_str(w[1]), w_str(w[2]))
    if t == 'inv':
        return "(%s)^-1" % w_str(w[1])
    if t == 'comm':
        return "[%s, %s]" % (w_str(w[1]), w_str(w[2]))
    if t == 'pow':
        return "(%s)^%d" % (w_str(w[1]), w[2])
    raise ValueError(w)


def w_mul(a, b):
    if a[0] == 'one':
        return b
    if b[0] == 'one':
        return a
    return ('mul', a, b)


def w_inv(a):
    if a[0] == 'one':
        return a
    if a[0] == 'inv':
        return a[1]
    return ('inv', a)


def w_pow(a, n):
    if n == 1:
        return a
    if n == 0:
        return ('one',)
    return ('pow', a, n)


# ---------------------------------------------------------------- sifting

def lead(g):
    """(position, value) of the first nonzero coordinate, or (15, 0) for the identity."""
    for r in range(15):
        if g[r] % N:
            return r, g[r] % N
    return 15, 0


def val2(x):
    """2-adic valuation of x in Z/8 (3 for x = 0)."""
    x %= N
    if x == 0:
        return 3
    e = 0
    while x % 2 == 0:
        x //= 2
        e += 1
    return e


def normalise(g, w):
    """Raise to an odd power so the leading coefficient becomes exactly 2^e."""
    r, v = lead(g)
    if r == 15:
        return g, w, 15, 0
    e = val2(v)
    u = v >> e                      # odd unit
    uinv = pow(u, -1, N)            # odd inverse mod 8
    if uinv % N == 1:
        return g, w, r, (1 << e)
    return power(g, uinv % N), w_pow(w, uinv % N), r, (1 << e)


class Table:
    """An induced polycyclic sequence for a subgroup, with words."""

    def __init__(self):
        self.tab = [None] * 15      # tab[r] = (elt, word, leadval)

    def sift(self, g, w=None):
        """Reduce g against the table.  Returns (residual_elt, residual_word).

        Invariant: g_original = residual * (product of table entries)^-1 ... precisely,
        we return (h, wh) with h = g * (stuff), wh the matching word, and h = 1 iff g is
        in the subgroup generated by the table.
        """
        if w is None:
            w = ('one',)
        while True:
            r, v = lead(g)
            if r == 15:
                return g, w
            ent = self.tab[r]
            if ent is None:
                return g, w
            e_ent = val2(ent[2])
            e_g = val2(v)
            if e_g < e_ent:
                return g, w
            c = (v >> e_ent) % (N >> e_ent)     # multiplier to cancel
            if c == 0:
                return g, w
            g = mul(g, power(inv(ent[0]), c))
            w = w_mul(w, w_pow(w_inv(ent[1]), c))

    def add(self, g, w):
        """Sift and insert; returns True if the subgroup grew."""
        pend = [(g, w)]
        grew = False
        while pend:
            g0, w0 = pend.pop()
            h, wh = self.sift(g0, w0)
            r, v = lead(h)
            if r == 15:
                continue
            grew = True
            h, wh, r, lv = normalise(h, wh)
            old = self.tab[r]
            self.tab[r] = (h, wh, lv)
            if old is not None:
                pend.append((old[0], old[1]))
        return grew

    def entries(self):
        return [(r, ent) for r, ent in enumerate(self.tab) if ent is not None]

    def order(self):
        o = 1
        for r, ent in self.entries():
            o *= N // ent[2]
        return o

    def contains(self, g):
        h, _ = self.sift(g)
        return lead(h)[0] == 15

    def certificate(self, g):
        """If g is in the subgroup, return a word w with w = g^-1 ... precisely a word
        `cert` such that eval(cert) == g."""
        h, wh = self.sift(g, ('one',))
        if lead(h)[0] != 15:
            return None
        # g * eval(wh) = 1  ==>  g = eval(wh)^-1
        return w_inv(wh)

    def close(self, gens_words, env, extra=()):
        """Close the table under powers, commutators of table entries, and commutators
        with the ambient generators (so the result is a genuine subgroup, and is normal
        under the given ambient generators when those are supplied in `extra`)."""
        for w in gens_words:
            self.add(w_eval(w, env), w)
        changed = True
        while changed:
            changed = False
            ents = [e for _, e in self.entries()]
            for (g, w, lv) in ents:
                p = N // lv
                if p > 1:
                    if self.add(power(g, p), w_pow(w, p)):
                        changed = True
            ents = [e for _, e in self.entries()]
            for i in range(len(ents)):
                for k in range(i + 1, len(ents)):
                    a, wa, _ = ents[i]
                    b, wb, _ = ents[k]
                    if self.add(commP(a, b), ('comm', wa, wb)):
                        changed = True
            for (g, w, lv) in [e for _, e in self.entries()]:
                for xw in extra:
                    x = w_eval(xw, env)
                    if self.add(commP(g, x), ('comm', w, xw)):
                        changed = True
        return self


def subgroup_closure(gen_words, env):
    """The subgroup generated by the given words."""
    t = Table()
    t.close(gen_words, env, extra=gen_words)
    return t


def commutator_subgroup(gen_words, env):
    """gamma_2 of the subgroup generated by gen_words: generated by the pairwise
    commutators, closed under commutation with the ambient generators (normal closure in
    H), which is exactly [H, H] since H/<that> is abelian."""
    t = Table()
    seeds = []
    for i in range(len(gen_words)):
        for k in range(i + 1, len(gen_words)):
            seeds.append(('comm', gen_words[i], gen_words[k]))
    t.close(seeds, env, extra=gen_words)
    return t


def lcs(gen_words, env, depth):
    """forceLcs H depth: forceLcs H 0 = H, forceLcs H (n+1) = [forceLcs H n, H]."""
    cur = subgroup_closure(gen_words, env)
    for _ in range(depth):
        seeds = []
        for _, (g, w, _lv) in cur.entries():
            for xw in gen_words:
                seeds.append(('comm', w, xw))
        nxt = Table()
        nxt.close(seeds, env, extra=gen_words)
        cur = nxt
    return cur


def named(**kw):
    t = [0] * 15
    for key, v in kw.items():
        t[COORDS.index(key)] = v % N
    return tuple(t)


def censKnob(t):
    return named(m=t)


def show(g):
    return "<" + ", ".join("%s=%d" % (COORDS[i], g[i]) for i in range(15) if g[i] % N) + ">" \
        if any(g) else "<1>"


def enumerate_table(t):
    """All elements of the subgroup, as (element, word) pairs, in canonical PC order."""
    ents = [ent for _, ent in t.entries()]
    out = [(ONE, ('one',))]
    for (g, w, lv) in reversed(ents):
        order = N // lv
        new = []
        for (h0, wh) in out:
            for e in range(order):
                if e == 0:
                    new.append((h0, wh))
                else:
                    new.append((mul(power(g, e), h0), w_mul(w_pow(w, e), wh)))
        out = new
    return out
