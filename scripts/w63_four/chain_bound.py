"""W63-FOUR, step 1: is the forcing at the four gap markings reachable by a Lean CHAIN?

A Lean proof of the stage-four forcing at a marking `m` needs an UPPER bound on
`forceLcs H 2 = [[H, H], H]`, `H = <letters>`.  Every such proof in this tree has the shape

    H <= K0            (`Subgroup.closure_le`: five letter memberships)
    [K0, K0] <= K1     (`Subgroup.commutator_le`)
    [K1, K0] <= K2     (`Subgroup.commutator_le`)

and the best `K2` a given `K0` can give is `gamma_3(K0)`, generated by the left-normed
commutators of weight three, four and five in a generating set of `K0`.  So the whole question
is: **which `K0` can a Lean file name?**

This script measures the answer for the richest family the tree can actually build - the
**filtered congruence subgroups** `K(V_1, ..., V_5) = {z : level_r(z) in V_r}` - and compares
`gamma_3(K0)` against what the forcing needs.

The forcing at these markings is `e_o not in B`, `B` the module of achievable shifts.  Because
`B` is a subgroup of the finite abelian group `gamma_3 = (Z/8)^6`, that holds iff some character
`psi` of `gamma_3` kills `B` and not `e_o`; and then the forcing is provable from any lattice
bound `forceLcs H 2 <= A_psi := intersection of the kernels of the five pullbacks of psi`.  So
`gamma_3(K0) <= A_psi` for one separating `psi` is EXACTLY the condition for the chain to work.

BRACKET CONVENTION.  [PAPER]
This script computes brackets in the paper convention, and its Lean target is written
with commP, the same convention.
Paper convention: commP x y = x^-1 y^-1 x y (GQ2/Words.lean:59, and every python commP
in scripts/).  Mathlib convention: [x, y] = x y x^-1 y^-1.  They are DIFFERENT families,
[x, y]_mathlib = commP x^-1 y^-1 (GradedFiveForce.commutatorElement_eq_commP), so a
paper-convention computation certifies a commP-written Lean statement and MIS-certifies a
[.,.]-written one.  Normal-closure and subgroup sifts are convention-IMMUNE.
"""

import fourlib as F


def separating_chars(d):
    """Characters of `gamma_3` killing every achievable shift but not the class-five unit."""
    B = F.image_span(d["mats"], d["Av"])
    return B, [c for c in F.characters(B) if c[5] % 8]


def pullbacks(d, c):
    """The five slot pullbacks `lambda_i = psi . Phi_i` of a character `psi` of `gamma_3`.

    `forceLcs H 2 <= A_psi` is exactly "every `lambda_i` kills the lattice", and since each
    `lambda_i` is linear it is enough to test a Howell basis.
    """
    return [tuple(F.dot(c, d["mats"][i][s]) for s in range(6)) for i in range(len(d["mats"]))]


def inside(basis, vs):
    return all(F.L.in_module(basis, v) for v in vs)


def report(name, m):
    print("== %s" % name)
    print("   letters: %s" % " | ".join(F.M.show(g) for g in m))
    d = F.marking_data(m)
    Av = d["Av"]
    print("   |forceLcs H 2| (wave-61 lattice) %d" % len(Av))
    B, sep = separating_chars(d)
    print("   |B| %d   class-five unit in B: %s   separating characters: %d"
          % (F.MD.card(B, 6), F.L.in_module(B, (0, 0, 0, 0, 0, 1)), len(sep)))

    V = F.filtered_hull(list(m))
    gens = F.hull_gens(V)
    print("   filtered congruence hull K0 of the letters: |K0| = %d" % F.hull_card(V))
    for r in range(5):
        print("      level %d span order %d   basis %s"
              % (r + 1, F.MD.card(V[r], F.LEVDIM[r]), V[r]))
    A0 = F.gamma3_of(gens)
    print("   |gamma_3(K0)| %d   contains the honest lattice: %s"
          % (F.MD.card(A0, 6), inside(A0, Av)))

    ok = [c for c in sep
          if all(F.dot(pullbacks(d, c)[i], v) == 0 for i in range(len(m)) for v in A0)]
    print("   separating characters that survive on gamma_3(K0): %d" % len(ok))
    for c in ok[:6]:
        print("      psi = %s" % F.show_char(c))
    if not ok:
        best = None
        for c in sep:
            lam = pullbacks(d, c)
            bad = sum(1 for i in range(len(m)) for v in A0 if F.dot(lam[i], v))
            if best is None or bad < best[0]:
                best = (bad, c, lam)
        print("   closest character psi = %s misses %d of %d slot/basis pairs"
              % (F.show_char(best[1]), best[0], len(m) * len(A0)))
    print()
    return d, sep, V, A0


if __name__ == "__main__":
    for (name, mm) in F.FOUR:
        report(name, mm)
