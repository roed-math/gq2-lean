# ---- honest subgroup closures -------------------------------------------------------------

def _close(seen, act):
    """Saturate `seen` under the unary maps `act`."""
    frontier = list(seen)
    while frontier:
        nxt = []
        for p in frontier:
            for f in act:
                q = f(p)
                if q not in seen:
                    seen.add(q)
                    nxt.append(q)
        frontier = nxt
    return seen


def gen_closure(gens, conj=()):
    """The subgroup generated by `gens`, closed under conjugation by `conj`.

    Generators already inside the current closure are skipped, so a large but redundant
    generating set costs no more than a minimal one.
    """
    seen = {ONE}
    act = []
    for g in conj:
        act.append(lambda p, g=g: M.conjP(p, g))
        act.append(lambda p, g=M.inv(g): M.conjP(p, g))
    for g in gens:
        if g in seen:
            continue
        act.append(lambda p, g=g: M.mul(p, g))
        act.append(lambda p, g=M.inv(g): M.mul(p, g))
        _close(seen, act)
    return seen


def comm_subgroup(Xgens, Y, conj):
    """`[<Xgens>^conj, <Y>]` for `Y` a generating set: the normal closure of the basic
    commutators.  Standard: if `D = <X>^H` and `H = <Y>` then `[D, H] = <[x, y]>^H`."""
    return gen_closure([M.commP(x, y) for x in Xgens for y in Y], conj=conj)


def lcs(letters):
    """`H`, `[H, H]` and `forceLcs H 2 = [[H, H], H]`, as explicit sets."""
    Y = list(letters)
    H = gen_closure(Y)
    D = comm_subgroup(Y, Y, Y)
    A = comm_subgroup(sorted(D), Y, Y)
    return H, D, A


# ---- the gamma_3 coordinates ---------------------------------------------------------------

def vecs(S):
    """The `(j, k, l, m, n, o)`-vectors of a set of `gamma_3`-shaped elements."""
    assert all(all(z[k] == 0 for k in range(9)) for z in S), "not gamma_3-shaped"
    return sorted({L.vec(z) for z in S})


def span_basis(vs, ncols=6):
    return MD.howell(list(vs), ncols)


# ---- Z/8-linear algebra on the gamma_3 coordinates -----------------------------------------

def dot(c, v):
    return sum(c[i] * v[i] for i in range(len(v))) % N


def characters(vs, ncols=6):
    """Every `Z/8`-linear functional on `(Z/8)^ncols` that kills the set `vs`.

    Only a spanning family of `vs` is tested, so pass a Howell basis when `vs` is large.
    """
    rows = list(vs)
    out = []
    for code in range(N ** ncols):
        c = []
        t = code
        for _ in range(ncols):
            c.append(t % N)
            t //= N
        if all(dot(c, v) == 0 for v in rows):
            out.append(tuple(c))
    return out


def show_char(c, names=COORD[9:]):
    """A functional as a readable linear form."""
    parts = ["%d%s" % (c[i], names[i]) for i in range(len(c)) if c[i]]
    return " + ".join(parts) if parts else "0"


# ---- filtered congruence subgroups ---------------------------------------------------------
#
# The five graded levels of `U_6(Z/8)`: level `r` is the `r`-th superdiagonal, so
# level 1 = (a, b, c, d, e), level 2 = (f, g, h, i), level 3 = (j, k, l), level 4 = (m, n),
# level 5 = (o).  A **filtered congruence subgroup** is a set of the shape
#
#     K(V_1, ..., V_5) = {z : level_r(z) in V_r for every r}
#
# with each `V_r` a `Z/8`-submodule.  It is a subgroup exactly when each `V_r` absorbs the
# multiplication cocycle of level `r`, which is what `filtered_hull` saturates.

LEVEL = [(0, 5), (5, 9), (9, 12), (12, 14), (14, 15)]
LEVDIM = [5, 4, 3, 2, 1]


def level(z, r):
    lo, hi = LEVEL[r - 1]
    return tuple(z[k] % N for k in range(lo, hi))


def lift(r, v):
    """The element whose level `r` is `v` and whose every other level is zero."""
    t = [0] * 15
    lo, _ = LEVEL[r - 1]
    for i, x in enumerate(v):
        t[lo + i] = x % N
    return tuple(t)


def _span(rows, ncols):
    return MD.howell([tuple(x % N for x in r) for r in rows], ncols) if rows else []


def _members(basis, ncols):
    return MD.members(basis, ncols) if basis else [(0,) * ncols]


def filtered_hull(seeds):
    """The smallest filtered congruence subgroup containing `seeds`.

    Saturates the level spans under the multiplication cocycles read straight off the matrix
    product: `f_{pq} = f_p + f_q + a_p b_q`, `j_{pq} = j_p + j_q + a_p g_q + f_p c_q`,
    `m_{pq} = m_p + m_q + a_p k_q + f_p h_q + j_p d_q`,
    `o_{pq} = o_p + o_q + a_p n_q + f_p l_q + j_p i_q + m_p e_q`, and the `b/g/k/n` mirrors.
    """
    V = [_span([level(z, r) for z in seeds], LEVDIM[r - 1]) for r in range(1, 6)]
    while True:
        B1, B2, B3, B4 = V[0], V[1], V[2], V[3]        # Howell bases; the cocycles are bilinear
        c2 = [(p[0] * q[1], p[1] * q[2], p[2] * q[3], p[3] * q[4]) for p in B1 for q in B1]
        c3 = ([(p[0] * q[1], p[1] * q[2], p[2] * q[3]) for p in B1 for q in B2]
              + [(p[0] * q[2], p[1] * q[3], p[2] * q[4]) for p in B2 for q in B1])
        c4 = ([(p[0] * q[1], p[1] * q[2]) for p in B1 for q in B3]
              + [(p[0] * q[2], p[1] * q[3]) for p in B2 for q in B2]
              + [(p[0] * q[3], p[1] * q[4]) for p in B3 for q in B1])
        c5 = ([(p[0] * q[1],) for p in B1 for q in B4]
              + [(p[0] * q[2],) for p in B2 for q in B3]
              + [(p[0] * q[3],) for p in B3 for q in B2]
              + [(p[0] * q[4],) for p in B4 for q in B1])
        new = [list(V[0]),
               _span(list(V[1]) + c2, 4), _span(list(V[2]) + c3, 3),
               _span(list(V[3]) + c4, 2), _span(list(V[4]) + c5, 1)]
        if all(MD.card(new[r], LEVDIM[r]) == MD.card(V[r], LEVDIM[r]) for r in range(5)):
            return new
        V = new


def hull_gens(V):
    """A generating set for the filtered congruence subgroup with level spans `V`."""
    return [lift(r + 1, v) for r in range(5) for v in V[r]]


def hull_card(V):
    c = 1
    for r in range(5):
        c *= MD.card(V[r], LEVDIM[r])
    return c


UNITS = [tuple(1 if t == k else 0 for t in range(15)) for k in range(15)]


def graded_hull(seeds, conj):
    """The smallest GRADED subgroup containing `seeds` and normalised by `conj`.

    Graded means `{z : level_r(z) in V_r}`; the saturation adds, at each round, the level parts
    of all products, inverses and `conj`-conjugates of the pure lifts of the current level
    bases.  Over-approximating is safe: every bound this produces is an upper bound for the
    subgroup a Lean chain would name.
    """
    V = [_span([level(z, r) for z in seeds], LEVDIM[r - 1]) for r in range(1, 6)]
    while True:
        gens = hull_gens(V)
        fresh = list(gens)
        for p in gens:
            fresh.append(M.inv(p))
            for q in gens:
                fresh.append(M.mul(p, q))
            for g in conj:
                fresh.append(M.conjP(p, g))
                fresh.append(M.conjP(p, M.inv(g)))
        new = [_span([level(z, r) for z in fresh] + list(V[r - 1]), LEVDIM[r - 1])
               for r in range(1, 6)]
        if all(MD.card(new[r], LEVDIM[r]) == MD.card(V[r], LEVDIM[r]) for r in range(5)):
            return new
        V = new


def comm_span(Pgens, Y, conj):
    """The `gamma_3`-submodule spanned by `[p, y]` for `p` in `Pgens`, `y` in `Y`, saturated
    under conjugation by `conj`.  This is the `K2` of a chain whose `K1` is generated by
    `Pgens`."""
    seeds = [M.commP(p, y) for p in Pgens for y in Y]
    assert all(all(z[k] == 0 for k in range(9)) for z in seeds), "not gamma_3-shaped"
    V = MD.howell([L.vec(z) for z in seeds], 6)
    while True:
        fresh = list(V)
        for v in V:
            p = L.elt(v)
            for g in conj:
                fresh.append(L.vec(M.conjP(p, g)))
                fresh.append(L.vec(M.conjP(p, M.inv(g))))
        new = MD.howell(list(V) + fresh, 6)
        if MD.card(new, 6) == MD.card(V, 6):
            return new
        V = new


def gamma3_of(gens):
    """A Howell basis of `gamma_3` of the subgroup generated by `gens`.

    `[[x, y], z]` and its two further brackets over the generators: exactly the chain bound
    `[[K, K], K]` a Lean file gets from `Subgroup.commutator_le` twice.
    """
    return L.gamma3_basis(list(gens))


# ---- the marking data ----------------------------------------------------------------------

def marking_data(m):
    """Everything the certificate search needs at one marking.

    The achievable lattice is wave 61's `gamma3_basis`, whose cardinality wave 61's
    `validate_sharp4.py` section 0 already checked against `pointlib`'s honest closure.
    """
    Ab = L.gamma3_basis(list(m))
    Av = sorted(MD.members(Ab, 6))
    mats = [L.slot_matrix(m, i) for i in range(len(m))]
    return {"Av": Av, "Abasis": Ab, "mats": mats, "letters": list(m), "relator": L.relator(m)}


def shift_of(mats, zs):
    """The stage-four shift of a five-slot dressing, by linearity of the slot matrices."""
    out = [0] * 6
    for i, w in enumerate(zs):
        im = L.apply_matrix(mats[i], w)
        out = [(out[t] + im[t]) % N for t in range(6)]
    return tuple(out)


def image_span(mats, Av):
    """`B`: the subgroup of `gamma_3` of all achievable stage-four shifts."""
    gens = [L.apply_matrix(mats[i], v) for i in range(len(mats)) for v in Av]
    return MD.howell(gens, 6)
