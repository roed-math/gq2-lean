"""W65-CONSOL: which BRACKET CONVENTION does each certification script's Lean target use?

W64-PSI4 found `scripts/w63_four/certify.py` computing its 216 weight-three brackets in the
PAPER convention

    commP x y = x^-1 y^-1 x y                (GQ2/Words.lean:59, and every python `commP`)

while the Lean it certified, `GradedStageFour.gapOneABr`, is written with MATHLIB's

    commutatorElement x y = x y x^-1 y^-1

The two are different families, related by `[x, y]_mathlib = commP x^-1 y^-1`
(`GradedFiveForce.commutatorElement_eq_commP`).  W64-VERIFY bounded the blast radius and
recommended that EVERY certification script carry a line naming which bracket its Lean target
uses.  This module computes the classification such a line records, from the Lean tree itself
rather than from a list typed by hand.

METHOD, in three steps, each auditable from the emitted table.

1  Scan `GQ2/` for declarations whose CODE (docstrings and `--` comments stripped first) uses
   the mathlib bracket.  Stripping matters: without it a declaration is flagged whenever the
   NEXT declaration's docstring happens to mention the bracket, which produced five false
   positives on the first pass here.
2  Separate ELEMENT-level uses from SUBGROUP-level ones.  A bracket of two subgroups is a
   commutator SUBGROUP, and `[H, K]` is generated by a set closed under inversion, so it is
   convention-IMMUNE: `[x, y]_mathlib = commP x^-1 y^-1` and the generated subgroup is the same
   either way.  This is W64-VERIFY's immunity observation, and it is what makes `forceLcs`,
   `LcsGens.lcsSeries` and `LcsGens.commLeft/commRight/commAll` irrelevant to the audit.
3  A script is at RISK exactly when it names one of the element-level declarations.

WHAT THE SCAN FINDS, and it is a SHORT list.  In the whole of `GQ2/`, the element-level mathlib
brackets are

    GradedStageFour.gapOneABr, gapOneBBr, gapTwoABr, gapTwoBBr    (W63-FOUR)
    GradedStageFourClosed.gapOneW, gapTwoW                        (W64-PSI4)

and nothing else.  WARNING: the second row is NEW IN WAVE 64 and is NOT in W64-VERIFY's
blast-radius statement, which says the four `gap*Br` censuses are the only mathlib-bracket
`decide`s in the tree.  W64-PSI4's own file docstring does flag it ("the same convention gap
bites the odd dressing below"), so the fact was known inside the wave and not folded into the
audit.  `gapOneW = [[gapOneS, gapOneV], gapOneV]` pairs to `3` in the paper convention and to
`7` in mathlib's, and `gapOneW_shift` proves `7`.
"""

import os
import re

LB = chr(0x2045)

DECL = re.compile(
    r"^(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+|noncomputable\s+)*"
    r"(theorem|lemma|def|abbrev|instance)\s+([A-Za-z0-9_.'!?]+)", re.M)

# a declaration body also ends at the first `#print`, `end ` or `open ` line after it: without
# this the LAST declaration of a file absorbs the whole AxiomPins section and is credited with
# every name printed there
STOP = re.compile(r"^(#print|#check|end\s|open\s|section\s|namespace\s|attribute\s)", re.M)


def _body(text, pos, end):
    seg = text[pos:end]
    m = STOP.search(seg, 1)
    return seg[: m.start()] if m else seg

IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_.']*")

# declarations whose bracket is between SUBGROUPS, hence convention-immune (step 2)
SUBGROUP_LEVEL = {
    "forceLcs", "commLeft", "commRight", "commAll", "lcsGensSet", "lcsSeries",
    "twoCentralSucc", "commLayerHom", "twoCentralSeries_units_le",
}


def strip_comments(txt):
    """Remove `/- ... -/` blocks (nesting-aware) and `--` line comments."""
    out = []
    depth = 0
    i = 0
    while i < len(txt):
        if txt.startswith("/-", i):
            depth += 1
            i += 2
            continue
        if txt.startswith("-/", i) and depth > 0:
            depth -= 1
            i += 2
            continue
        if depth == 0:
            out.append(txt[i])
        i += 1
    return re.sub(r"--[^\n]*", "", "".join(out))


def lean_bracket_decls(root="GQ2"):
    """[(file, kind, name, closed_by_decide)] for every code-level mathlib-bracket use."""
    res = []
    for dp, _, ns in os.walk(root):
        for n in sorted(ns):
            if not n.endswith(".lean"):
                continue
            f = os.path.join(dp, n)
            t = strip_comments(open(f, encoding="utf-8").read())
            marks = [(m.start(), m.group(1), m.group(2)) for m in DECL.finditer(t)]
            for i, (pos, kind, name) in enumerate(marks):
                end = marks[i + 1][0] if i + 1 < len(marks) else len(t)
                body = _body(t, pos, end)
                if LB in body:
                    res.append((f, kind, name, bool(re.search(r"\bdecide\b", body))))
    return res


def element_level_names(root="GQ2"):
    """The names a script can be WRONG about: element-level mathlib brackets."""
    names = {}
    for f, kind, name, dec in lean_bracket_decls(root):
        if name in SUBGROUP_LEVEL:
            continue
        # a declaration that merely CONSUMES a subgroup-level name is not itself at risk
        names.setdefault(name, (f, kind, dec))
    # drop consumers: keep only defs, and theorems that are not about subgroup containment
    out = {}
    for name, (f, kind, dec) in names.items():
        if kind in ("def", "abbrev"):
            out[name] = (f, kind, dec)
    return out


def risky_lean_names(root="GQ2"):
    """Element-level bracket definitions, plus the theorems stated in terms of them."""
    base = element_level_names(root)
    risky = dict(base)
    for dp, _, ns in os.walk(root):
        for n in sorted(ns):
            if not n.endswith(".lean"):
                continue
            f = os.path.join(dp, n)
            t = strip_comments(open(f, encoding="utf-8").read())
            marks = [(m.start(), m.group(1), m.group(2)) for m in DECL.finditer(t)]
            for i, (pos, kind, name) in enumerate(marks):
                end = marks[i + 1][0] if i + 1 < len(marks) else len(t)
                body = _body(t, pos, end)
                if name in risky:
                    continue
                if set(IDENT.findall(body)) & set(base):
                    risky[name] = (f, kind, bool(re.search(r"\bdecide\b", body)))
    return risky


def script_files(scripts_root="scripts"):
    out = []
    for d in sorted(os.listdir(scripts_root)):
        if not (d.startswith("w5") or d.startswith("w6")):
            continue
        p = os.path.join(scripts_root, d)
        if not os.path.isdir(p):
            continue
        for n in sorted(os.listdir(p)):
            if n.endswith(".py"):
                out.append(os.path.join(p, n))
    return sorted(out)


BRACKETY = ("commp", "commutator", "bracket")
SIFTY = ("gen_closure", "subgroup(", "normal_closure", "derived_of")
RAW_NESTED = re.compile(r"commP\(\s*[A-Za-z_][A-Za-z0-9_.]*\.?commP\(")


MARK = "BRACKET CONVENTION."


def drop_block(text):
    """Remove a previously inserted convention block, so classification never reads its own
    output back in (the first run of `add_convention.py` otherwise reclassifies a PAPER script
    as MATHLIB because the block it just wrote names `gapOneABr`)."""
    i = text.find(MARK)
    if i == -1:
        return text
    j = text.find("convention-IMMUNE.", i)
    if j == -1:
        return text
    return text[:i] + text[text.find("\n", j) + 1:]


def raw_signals(path):
    """(computes brackets, sifts them into a closure, builds a RAW nested bracket)."""
    txt = drop_block(open(path, encoding="utf-8").read())
    low = txt.lower()
    return (any(t in low for t in BRACKETY),
            any(t in low for t in SIFTY),
            bool(RAW_NESTED.search(txt)))


def classify(path, risky, dir_mathlib=frozenset()):
    """(verdict, evidence).  MATHLIB > PAPER-RAW > IMMUNE > PAPER > NONE.

    MATHLIB    the Lean target is written with mathlib's bracket, so a paper-convention
               computation here certifies a DIFFERENT set.  Two routes to this verdict: the
               script names a risky Lean declaration, or it builds a raw nested bracket and
               lives in a wave directory whose Lean target is one of the risky ones.
    PAPER-RAW  builds a raw nested bracket set against a `commP`-written Lean target: correct
               as it stands, and the place a future convention slip would bite.
    IMMUNE     brackets only ever enter a closure, so the convention cannot be seen.
    PAPER      computes brackets, all single-weight, against a `commP`-written target.
    NONE       computes no commutators.
    """
    txt = drop_block(open(path, encoding="utf-8").read())
    named = sorted(set(IDENT.findall(txt)) & set(risky))
    has_bracket, has_sift, nested = raw_signals(path)
    d = os.path.basename(os.path.dirname(path))
    if named:
        return "MATHLIB", named
    if nested and d in dir_mathlib:
        return "MATHLIB", ["(directory target)"]
    if nested:
        return "PAPER-RAW", []
    if not has_bracket:
        return "NONE", []
    if has_sift:
        return "IMMUNE", []
    return "PAPER", []


# A wave directory whose Lean target carries element-level mathlib brackets but whose scripts
# never spell the Lean name out.  `w63_four` certifies `GQ2/Dyadic/SqCore/GradedStageFour.lean`,
# whose `gapOneABr` .. `gapTwoBBr` are `[[L a, L b], L c]` in mathlib's bracket; W64-PSI4 found
# this and re-ran the census in the right convention (`scripts/w64_psi4/close.py` part D).
KNOWN_MATHLIB_DIRS = {"w63_four"}


def mathlib_directories(risky, scripts_root="scripts"):
    """Wave directories at least one of whose scripts names a risky Lean declaration."""
    out = set(KNOWN_MATHLIB_DIRS)
    for f in script_files(scripts_root):
        if set(IDENT.findall(drop_block(open(f, encoding="utf-8").read()))) & set(risky):
            out.add(os.path.basename(os.path.dirname(f)))
    out.discard("w65_consol")
    return out
