"""W59-FORCE5 step 3: an EXPLICIT achievable gamma_3-element that kills the dressed frame.

`scope_probe.py` found that at the class-five point gamma_3 of the image contains the whole of
gamma_4 of the ambient carrier - in particular the gamma_4-SHAPED element `<m = 1>`, whose
class-four coordinate is odd and which therefore lies outside gamma_4 of the image.  Dressing
the sigma slot by it kills the `a0 = a1`-dressed frame outright.

This script produces a short, checkable word for such an element, so the finding can be stated
in Lean as an identity rather than as a census.

BRACKET CONVENTION.  [PAPER]
This script computes brackets in the paper convention, and its Lean target is written
with commP, the same convention.
Paper convention: commP x y = x^-1 y^-1 x y (GQ2/Words.lean:59, and every python commP
in scripts/).  Mathlib convention: [x, y] = x y x^-1 y^-1.  They are DIFFERENT families,
[x, y]_mathlib = commP x^-1 y^-1 (GradedFiveForce.commutatorElement_eq_commP), so a
paper-convention computation certifies a commP-written Lean statement and MIS-certifies a
[.,.]-written one.  Normal-closure and subgroup sifts are convention-IMMUNE.
"""
import sys
import os

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "w58_sigma5"))

import u6mat as M                                             # noqa: E402
import u6lib as W58                                           # noqa: E402

sigma, X, Y, U, V = M.sigFiveMark, M.sepX, M.sepY, M.sepU, M.sepV
letters = [sigma, X, Y, U, V]
NAME = {sigma: "sigma", X: "x0", Y: "x1", U: "U", V: "V"}


def note(s):
    print("   " + s)


print("== a short word for a gamma_4-shaped, gamma_3-achievable killing dressing ==")

# gamma_2 of the image is generated by the letter commutators, closed under conjugation.
# Every triple commutator [[a, b], c] lies in gamma_3 of the image; look for one whose
# class-three coordinates vanish and whose class-four coordinate is ODD.
best = []
for a in letters:
    for b in letters:
        w = W58.commP(a, b)
        for c in letters:
            z = W58.commP(w, c)
            if z[9] == 0 and z[10] == 0 and z[11] == 0 and z[12] % 2 == 1:
                best.append(("[[%s, %s], %s]" % (NAME[a], NAME[b], NAME[c]), z))
print("   triple commutators that are gamma_4-shaped with ODD class-four coordinate:")
for nm, z in best[:8]:
    note("  %-24s = %s" % (nm, M.show(z)))
note("  (%d found)" % len(best))

# ...and check that dressing the sigma slot by one of them kills the dressed frame.
base = [W58.mul(sigma, X), X, Y, U, V]
print()
print("== the kill ==")
for nm, z in best[:8]:
    m = list(base)
    m[0] = W58.mul(m[0], z)
    r = W58.sqRelWord(m)
    note("sigma slot dressed by %-24s -> relator %s   %s"
         % (nm, M.show(r), "KILLS" if r == M.ONE else ""))

print()
print("== the same element, with its gamma_4-of-the-image status ==")
for nm, z in best[:3]:
    note("%-24s = %s : class-four coordinates (m, n) = (%d, %d), m ODD, so it is NOT in"
         % (nm, M.show(z), z[12], z[13]))
    note("%s gamma_4 of the image (every element of which is even in both)" % (" " * 26))
