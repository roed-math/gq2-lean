"""W60-STAGE4: Howell forms over Z/8, and gamma_3 of an image subgroup as a MODULE.

`gamma_3` of the ambient carrier is abelian - `[gamma_3, gamma_3] <= gamma_6 = 1` - and the
group law on it is coordinatewise addition in `(j, k, l, m, n, o)`.  So `gamma_3(im)` is a
Z/8-submodule of `(Z/8)^6`, and the expensive element-by-element closure of `pointlib` can be
replaced by a Howell basis.  Generators, all legitimate because `[-, c]` is a homomorphism on
`gamma_3` (its commutators with the image land in `gamma_7 = 1`):

    gamma_3(im) = span { [[a,b],c] }  +  gamma_4(im)
    gamma_4(im) = span { [t, c] : t in the above }  +  gamma_5(im)
    gamma_5(im) = span { [u, c] : u in the above }

`sanity_mod.py` checks the Howell cardinality against `pointlib`'s honest closure at the
wave-59 point, and the extracted gamma_4-shaped submodule against the honest one.

The Howell form is used for exactly the property it exists for: the elements of the module
whose first `t` coordinates vanish are generated by the basis rows whose first `t` coordinates
vanish.  That is what extracts the `gamma_4`-SHAPED part of `gamma_3(im)`, which is the object
the wave-59 hole is about.
"""

N = 8


def val2(x):
    """The 2-adic valuation of x in Z/8, with val2(0) = 3."""
    x %= N
    if x == 0:
        return 3
    v = 0
    while x % 2 == 0:
        x //= 2
        v += 1
    return v


INV = {1: 1, 3: 3, 5: 5, 7: 7}


def howell(rows, ncols):
    """A Howell basis of the Z/8-submodule of (Z/8)^ncols spanned by `rows`."""
    pool = [tuple(x % N for x in r) for r in rows]
    pool = [r for r in pool if any(r)]
    basis = []
    for c in range(ncols):
        # every row still in the pool is already zero in columns < c
        idx = [i for i, r in enumerate(pool) if r[c]]
        if not idx:
            continue
        v = min(val2(pool[i][c]) for i in idx)
        p = next(i for i in idx if val2(pool[i][c]) == v)
        u = pool[p][c] >> v                              # an odd unit
        piv = tuple((INV[u] * x) % N for x in pool[p])   # now piv[c] = 2^v
        rest = []
        for i, r in enumerate(pool):
            if i == p:
                continue
            if r[c]:
                q = r[c] >> v                            # exact: v is minimal
                r = tuple((r[k] - q * piv[k]) % N for k in range(ncols))
            if any(r):
                rest.append(r)
        tor = tuple(((N >> v) * x) % N for x in piv)
        if any(tor):
            rest.append(tor)
        basis.append(piv)
        pool = rest
    return basis


def card(basis, ncols):
    """The order of the module from its Howell basis (one pivot per pivot column)."""
    total = 1
    for r in basis:
        c = next(i for i in range(ncols) if r[i] % N)
        total *= N >> val2(r[c])
    return total


def members(basis, ncols, cap=100000):
    """Enumerate the module (small ones only)."""
    seen = {(0,) * ncols}
    frontier = [(0,) * ncols]
    while frontier:
        nxt = []
        for p in frontier:
            for g in basis:
                q = tuple((p[i] + g[i]) % N for i in range(ncols))
                if q not in seen:
                    seen.add(q)
                    nxt.append(q)
                    if len(seen) > cap:
                        raise RuntimeError("module too large")
        frontier = nxt
    return seen


def sub_zero_prefix(basis, t):
    """The rows of a Howell basis whose first `t` coordinates vanish: a basis of the
    submodule of elements with vanishing first `t` coordinates."""
    return [r for r in basis if all(r[i] % N == 0 for i in range(t))]
