// W56-ALPHA2.  Does the wave-52 range identity ever produce alpha = 2?
//
// For a finite extension L/Q_2 the wave-52 identity `evenRange_range_eq`
// (GQ2/Dyadic/Instances/EvenCyclotomicRange.lean) says that, when L(i)/L is ramified,
//    range(chi_cyc on G_L(2))  =  imChiM alpha  =  {+-1}*(1 + 2^alpha Z_2)      (-1 in range)
//    range(chi_cyc on G_L(2))  =  imChiN alpha  =  closure< -(1+2^alpha)^-1 >   (-1 notin range)
// for a unique alpha >= 2 determined by L.  This script computes that alpha exactly for
// every 2-adic field of small degree.
//
// WHAT H IS.  H := range chi = image of Gal(L(mu_{2^oo})/L) in Z_2^*, i.e. the subgroup of
// Z_2^* = Gal(Q_2(mu_{2^oo})/Q_2) fixing F := L cap Q_2(mu_{2^oo}).  So [Z_2^* : H] = [F:Q_2],
// which divides d = [L:Q_2].
//
// EXACTNESS.  Because [Z_2^*:H] divides d and Z_2^* is abelian, (Z_2^*)^d <= H, and
// (Z_2^*)^d = 1 + 2^(v_2(d)+2) Z_2 for even d (= Z_2^* for odd d).  Hence H is determined by
// H mod 2^n as soon as n >= v_2(d)+2.  We take n = v_2(d)+3, at least 5.
//
// HOW H IS COMPUTED.  For each subgroup H' of (Z/2^n)^* the fixed field F_{H'} of H' inside
// Q(zeta_{2^n}) is generated by the Gaussian period  eta_{H'} = sum_{a in H'} zeta^a, whose
// minimal polynomial over Q we compute once.  Then
//        F_{H'} embeds into L   <=>   H' contains H,
// so H is the intersection of all H' whose period polynomial has a root in L.  Every step is
// a root test in L: exact, no sampling.
//
// CROSS-CHECK 1 (independent, class field theory).  chi_L(rec_L x) = (unit part of
// N_{L/Q_2} x)^{-1}, so unit parts of actual norms all lie in H.  We generate a subgroup S
// from real norms and report S = H or S < H.
// CROSS-CHECK 2 (the lane's structural claim).  alpha >= 3  <=>  sqrt(2) in L.

SetQuitOnError(true);

PREC := 200;
Q := pAdicField(2, PREC);
Zx<x> := PolynomialRing(Integers());

// ------------------------------------------------------ subgroup machinery mod 2^n

function GenSub(gens, m)
  S := {Integers() | 1};
  repeat
    old := S;
    S := S join {(a*b) mod m : a in S, b in gens};
  until S eq old;
  return S;
end function;

function AllSubgroups(n)
  m := 2^n;
  U := [a : a in [1 .. m - 1] | IsOdd(a)];
  subs := {};
  for a in U do
    for b in U do
      Include(~subs, GenSub([a, b], m));
    end for;
  end for;
  return subs;
end function;

// Defining polynomial over Q of the fixed field of H' inside Q(zeta_{2^n}).
// The naive Gaussian period sum_{a in H'} zeta^a degenerates to 0 for 2-power conductors
// (any H' containing 1 + 2^(n-1) kills it), so we average a random element instead and
// verify the degree, which certifies primitivity.
function PeriodPoly(Hp, n)
  m := 2^n;
  C<zt> := CyclotomicField(m);
  idx := (2^(n-1)) div #Hp;
  for tries in [1 .. 60] do
    c := [Random(0, 30) : j in [0 .. m - 1]];
    eta := &+[ &+[c[j+1] * zt^((a*j) mod m) : j in [0 .. m - 1]] : a in Hp];
    mp := MinimalPolynomial(eta);
    if Degree(mp) eq idx then return Zx ! mp; end if;
  end for;
  error "PeriodPoly: no primitive element found";
end function;

// alpha and branch, from H given as a set of residues mod 2^n
function AlphaOf(H, n)
  m := 2^n;
  if (m - 1) in H then                       // -1 in H : M branch, H = {+-1}(1+2^b)
    b := n;
    for h in H do
      if h ne 1 and (h mod 4) eq 1 then
        v := Valuation(h - 1, 2);
        if v lt b then b := v; end if;
      end if;
    end for;
    return "M", Maximum(2, b);
  else                                       // N branch: alpha = min v_2(h+1) over h = 3 mod 4
    a := n;
    ok := false;
    for h in H do
      if (h mod 4) eq 3 then
        ok := true;
        v := Valuation(h + 1, 2);
        if v lt a then a := v; end if;
      end if;
    end for;
    if not ok then return "*", 0; end if;    // H <= 1+4Z_2 : i in L, out of class
    return "N", a;
  end if;
end function;

// ------------------------------------------------------ per-field computation

procedure Census(d, ~tally)
  n := Maximum(5, Valuation(d, 2) + 3);
  m := 2^n;
  printf "\n=========== degree %o over Q_2   (H determined mod 2^%o) ===========\n", d, n;
  if d eq 1 then
    exts := [Q];
  else
    exts := [FieldOfFractions(R) : R in AllExtensions(Q, d)];
  end if;
  printf "fields of degree %o : %o\n", d, #exts;
  printf "%-6o %-4o %-4o %-7o %-9o %-7o %-7o %-6o %-6o\n",
     "idx", "e", "f", "i in L", "L(i)/L", "sqrt2", "branch", "alpha", "norms";
  subs := Setseq(AllSubgroups(n));
  polys := [PeriodPoly(Hp, n) : Hp in subs];
  printf "subgroups of (Z/2^%o)^* : %o\n", n, #subs;
  idx := 0;
  for L in exts do
    idx := idx + 1;
    if d eq 1 then e := 1; f := 1; else e := RamificationIndex(L); f := InertiaDegree(L); end if;
    Ly<y> := PolynomialRing(L);
    hasI  := HasRoot(y^2 + 1, L);
    hasS2 := HasRoot(y^2 - 2, L);
    if hasI then
      kiram := "n/a";
    else
      U := UnramifiedExtension(L, 2);
      Uz<z> := PolynomialRing(U);
      kiram := HasRoot(z^2 + 1, U) select "unram" else "ram";
    end if;

    // ---- exact H : intersect every subgroup whose fixed field embeds in L
    H := {a : a in [1 .. m - 1] | IsOdd(a)};
    for t in [1 .. #subs] do
      if HasRoot(Ly ! polys[t], L) then H := H meet subs[t]; end if;
    end for;
    br, al := AlphaOf(H, n);

    // ---- cross-check 1: norms really do land in H, and generate it
    gens := [Integers() | ];
    piL := UniformizingElement(L);
    NB := Norm(piL, Q);
    Append(~gens, Integers()!(Integers(m)!(Integers()!(NB / 2^Valuation(NB)))));
    bas := [L!1];
    try
      bas := Basis(L, Q);
    catch err
      bas := [L.1^j : j in [0 .. d - 1]];
    end try;
    for t in [1 .. 300] do
      u := &+[Random(0, m*8) * bas[j] : j in [1 .. #bas]];
      if Valuation(u) ne 0 then continue; end if;
      Nu := Norm(u, Q);
      Append(~gens, Integers()!(Integers(m)!(Integers()!(Nu / 2^Valuation(Nu)))));
    end for;
    S := GenSub(gens, m);
    sub := (S subset H) select (S eq H select "=H" else "<H") else "!!BAD";

    inclass := (not hasI) and (kiram eq "ram");
    if inclass then
      key := <br, al>;
      b, v := IsDefined(tally, key);
      tally[key] := b select v + 1 else 1;
      pred := hasS2 select 3 else 2;
      got := (al ge 3) select 3 else 2;
      flag := (pred eq got) select "" else "   <<< sqrt2 CRITERION MISMATCH";
    else
      flag := "   (out of class)";
    end if;
    printf "%-6o %-4o %-4o %-7o %-9o %-7o %-7o %-6o %-6o%o\n",
      idx, e, f, hasI, kiram, hasS2, br, al, sub, flag;
  end for;
end procedure;

tally := AssociativeArray();
for d in [1, 2, 3, 4, 6] do
  Census(d, ~tally);
end for;

printf "\n=========== tally over the in-class fields of degree 1,2,3,4,6 ===========\n";
for k in Sort([kk : kk in Keys(tally)]) do
  printf "  branch %o  alpha = %o :  %o fields\n", k[1], k[2], tally[k];
end for;
printf "\ndone\n";
quit;
