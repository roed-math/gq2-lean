N = 8
ONE = M.ONE
IA, IB, IC, ID, IE = 0, 1, 2, 3, 4
IF, IG, IH, II = 5, 6, 7, 8
IJ, IK, IL = 9, 10, 11
IM, IN, IO = 12, 13, 14

# coordinates in class order: the layered solve fixes them in this order
CLASS_ORDER = [IA, IB, IC, ID, IE, IF, IG, IH, II, IJ, IK, IL, IM, IN, IO]


# ---- the class-five increment pairing --------------------------------------------------

def incr_pair(X, U, V, z0, z3, z4):
    """The handle+sigma part of the five-slot increment of `GradedFiveForce.sqRelWord_fiveLift`:

        (z0.m * X.e - z0.n * X.a) + (z3.m * V.e - z3.n * V.a) + (U.a * z4.n - U.e * z4.m).

    `X` is the x0-slot, `U`, `V` the two handle slots.  The exponent-slot part
    `-4 w1.o + 2 w2.o` is even for free and is not part of the pairing.
    """
    return ((z0[IM] * X[IE] - z0[IN] * X[IA])
            + (z3[IM] * V[IE] - z3[IN] * V[IA])
            + (U[IA] * z4[IN] - U[IE] * z4[IM])) % N


def incr_full(X, U, V, z0, w1, w2, z3, z4):
    """The whole increment, exponent slots included."""
    return (incr_pair(X, U, V, z0, z3, z4) - 4 * w1[IO] + 2 * w2[IO]) % N


def covectors(X, U, V):
    """The three mod-2 covectors `(slot.e, slot.a)` that read an achievable `(m, n)`."""
    return (((X[IE] % 2), (X[IA] % 2)),
            ((V[IE] % 2), (V[IA] % 2)),
            ((U[IE] % 2), (U[IA] % 2)))


def annihilates(cov, lat):
    """Does the mod-2 covector `cov = (ce, ca)` kill every `(m, n)` of `lat`?"""
    return all((ce * mm - ca * nn) % 2 == 0 for (mm, nn) in lat for (ce, ca) in [cov])


def five_orth(X, U, V, lam4):
    """THE SHARP INVARIANT: all three covectors annihilate the achievable `(m, n)`-lattice."""
    return all(annihilates(c, lam4) for c in covectors(X, U, V))


# ---- the graded lattices of a marking's image ------------------------------------------

def span(vecs, dim):
    """The additive subgroup of `(Z/8)^dim` generated by `vecs`."""
    seen = {(0,) * dim}
    frontier = [(0,) * dim]
    gens = sorted({v for v in vecs if any(v)})
    while frontier:
        nxt = []
        for p in frontier:
            for g in gens:
                q = tuple((p[k] + g[k]) % N for k in range(dim))
                if q not in seen:
                    seen.add(q)
                    nxt.append(q)
        frontier = nxt
    return seen


def pair2(p, q):
    """(f, g, h, i) of [p, q] for abelian columns p, q."""
    return ((p[0] * q[1] - p[1] * q[0]) % N, (p[1] * q[2] - p[2] * q[1]) % N,
            (p[2] * q[3] - p[3] * q[2]) % N, (p[3] * q[4] - p[4] * q[3]) % N)


def pair3(w, v):
    """(j, k, l) of [z, g] for z in gamma_2 with (f,g,h,i) = w, g with abelian columns v."""
    return ((-w[1] * v[0] + w[0] * v[2]) % N, (-w[2] * v[1] + w[1] * v[3]) % N,
            (-w[3] * v[2] + w[2] * v[4]) % N)


def pair4(z, v):
    """(m, n) of [z, g] for z in gamma_3 with (j,k,l) = z, g with abelian columns v."""
    return ((z[0] * v[3] - z[1] * v[0]) % N, (z[1] * v[4] - z[2] * v[1]) % N)


def lattices(letters):
    """`(A, Lam2, Lam3, Lam4)` for the image of a marking with the given slot values.

    `A` is the abelian image, `Lam_k` the class-`k` image of `gamma_k` of the image, so
    `Lam4` is exactly the achievable `gamma_4`-dressings' `(m, n)`-image.
    """
    abel = [(g[0], g[1], g[2], g[3], g[4]) for g in letters]
    A = span(abel, 5)
    # `pair2`, `pair3`, `pair4` are bilinear, so spanning over the GENERATORS gives the same
    # subgroup as spanning over the whole abelian image; `verify_lattices` checks that.
    L2 = span([pair2(p, q) for p in abel for q in abel], 4)
    L3 = span([pair3(w, v) for w in L2 for v in abel], 3)
    L4 = span([pair4(z, v) for z in L3 for v in abel], 2)
    return A, L2, L3, L4


def lattices_slow(letters):
    """The same four lattices, spanned over the WHOLE abelian image rather than over the
    letters, which is how `scripts/w59_force5/verify_force5.py` computed them."""
    abel = [(g[0], g[1], g[2], g[3], g[4]) for g in letters]
    A = span(abel, 5)
    L2 = span([pair2(p, q) for p in A for q in A], 4)
    L3 = span([pair3(w, v) for w in L2 for v in A], 3)
    L4 = span([pair4(z, v) for z in L3 for v in A], 2)
    return A, L2, L3, L4


def lam4_even(lam4):
    """W59's soundness CONSEQUENCE: every achievable `gamma_4`-dressing lies in `forceN4`."""
    return all(mm % 2 == 0 and nn % 2 == 0 for (mm, nn) in lam4)


def letters_even(letters, idx):
    """Every slot value has an even coordinate `idx`.  `idx = IC` is W59's `forceN1`."""
    return all(g[idx] % 2 == 0 for g in letters)


# ---- honest subgroup closure, for the independent check --------------------------------

def subgroup(seeds, conj_gens):
    """The smallest conjugation-closed subgroup containing `seeds` (wave 59's engine)."""
    seen = {ONE}
    gens = []
    for s in sorted({t for t in seeds if t != ONE}):
        if s in seen:
            continue
        gens.append(s)
        gens.append(M.inv(s))
        changed = True
        while changed:
            changed = False
            for p in list(seen):
                for g in gens:
                    q = M.mul(p, g)
                    if q not in seen:
                        seen.add(q)
                        changed = True
                for c in conj_gens:
                    q = M.conjP(p, c)
                    if q not in seen:
                        seen.add(q)
                        changed = True
    return seen


def gamma34(letters):
    """`(gamma_3, gamma_4)` of the image, by honest closure under the group law."""
    g3 = subgroup([M.commP(M.commP(a, b), c)
                   for a in letters for b in letters for c in letters], letters)
    g4 = subgroup([M.commP(z, g) for z in g3 for g in letters], letters)
    return g3, g4


# ---- the marking, its relator, and the five-slot refinement ----------------------------

def relator(S, X, Y, U, V, lib=M):
    """`sqRelWord` of the one-handle-live five-tuple: `sqWord S X Y * commP U V`
    (`GradedFive.sqRelWord_fiveTuple`), the same at every handle count and every handle."""
    return lib.mul(lib.sqWord(S, X, Y), lib.commP(U, V))


def frelator(S, X, Y, U, V):
    """…the same, through the fast product; `fastu6.crosscheck` gates its use."""
    return F.relator(S, X, Y, U, V)


def refined(S, X, Y, U, V, z0, w1, w2, z3, z4, lib=M):
    """`sqRelWord (fiveLift j m z0 w1 w2 z3 z4)`, evaluated honestly."""
    return relator(lib.mul(S, z0), lib.mul(X, w1), lib.mul(Y, w2),
                   lib.mul(U, z3), lib.mul(V, z4), lib)


def is_central(p):
    return all(p[k] == 0 for k in range(14))


def admissible(S, X, Y, U, V):
    """The census's admissibility condition: the relator is CENTRAL with an ODD residue,
    which is the class-five form of wave 59's `hres` + `hva`."""
    r = relator(S, X, Y, U, V)
    return is_central(r) and r[IO] % 2 == 1


# ---- the layered solve for the x1-slot -------------------------------------------------

def feasible2(S, X, U, V):
    """A one-evaluation necessary condition for admissibility.

    The relator's class-one rows are `-4 X_k + 2 Y_k`, so `Y_k = 2 X_k` zeroes them; the
    class-two rows then have coefficient `2` in `Y`, so they can only be zeroed if they are
    already EVEN.  Most letter tuples fail here, and failing here is 300 times cheaper than
    exhausting the layered solve."""
    Y = tuple((2 * X[k]) % N if k <= IE else 0 for k in range(15))
    r = F.relator(S, X, Y, U, V)
    return all(r[k] == 0 for k in range(IA, IE + 1)) and all(r[k] % 2 == 0
                                                             for k in range(IF, II + 1))


def solve_Y(S, X, U, V, want=1, odd_only=True, budget=200000):
    """All `Y` (up to `want`) making `sqWord S X Y * commP U V` central.

    The relator's class-`c` row depends only on `Y`'s coordinates of class `<= c`, so the
    coordinates can be fixed in class order; the top row is not adjustable by `Y.o` (its
    coefficient is `2`), which is exactly the class-five selection bit.
    """
    out = []
    state = {"n": 0}

    def rec(pos, Y):
        if len(out) >= want or state["n"] > budget:
            return
        if pos == 14:                                    # o-row: parity is not adjustable
            r = frelator(S, X, Y, U, V)
            if is_central(r) and (not odd_only or r[IO] % 2 == 1):
                out.append(Y)
            return
        k = CLASS_ORDER[pos]
        for v in range(N):
            state["n"] += 1
            Yv = Y[:k] + (v,) + Y[k + 1:]
            if frelator(S, X, Yv, U, V)[k] == 0:
                rec(pos + 1, Yv)
                if len(out) >= want:
                    return

    rec(0, ONE)
    return out


# ---- the independent kill search -------------------------------------------------------

def kill_exists(S, X, Y, U, V, g4, lib=F):
    """Does SOME achievable five-slot refinement kill the relator?  Honest: the refinement is
    built, the group law is run, and the result is compared with the identity.  `g4` is the
    achievable `gamma_4`-lattice as a set of honest group elements."""
    g5 = [M.liftC(t) for t in range(N)]
    for w2 in g5:
        for z in g4:
            for slot in range(3):
                trip = [ONE, ONE, ONE]
                trip[slot] = z
                if refined(S, X, Y, U, V, trip[0], ONE, w2, trip[1], trip[2], lib) == ONE:
                    return True
    return False


def gaFour_elements(lam4):
    """`gamma_4`-shaped group elements realising the achievable `(m, n)`-lattice, with the
    class-five coordinate set to zero.

    That loses nothing.  A class-five central factor on any of the three dressed slots leaves
    the relator unchanged: the sigma slot is conjugated by it and conjugation fixes the centre,
    and a handle commutator absorbs it (`commP_mul_liftC6_left/right`).  So two achievable
    dressings with the same `(m, n)` produce the same refinement, and the kill search sweeps
    `w2` over the whole of `gamma_5` independently."""
    return [M.named(m=mm, n=nn) for (mm, nn) in sorted(lam4)]
