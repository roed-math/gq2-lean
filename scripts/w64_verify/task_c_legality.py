"""W64-VERIFY task C: the ArbFrames legality question, at all three points by ONE criterion.

The tree answers "no LEGAL dressing `g` has `Phi g = x0`" three times at three points by three
incomparable single-column arguments (wave 60 off `lambda + nu'` mod 2; wave 61 off the fifth
abelian column using `7` a unit; W63-LIVE5 off the FIRST abelian column, the fifth being
reachable there since `3 * 7 = 5`).  This script tests whether one statement covers all three.

THE CANDIDATE STATEMENT.  The five abelian coordinates `a, b, c, d, e` of `SqU6` are group
homomorphisms, so on the subgroup generated by the five letters the abelian part of `Phi g`
depends only on the exponent vector `(a_s, a_0, a_1, a_U, a_V)` and is `M . exponents`, where
`M` is the point's `5 x 5` matrix of abelian columns.  Legality is a condition on the exponents
ALONE and is the SAME condition at every point:

    lambda g = c a_s + a_0 + 2 a_1 = 0   (c = sqPivotExp, a unit; lambda kills every handle)
    nu'    g = a_s = 0                   (at a fully cleared row)

so the legal exponent vectors form the point-independent lattice

    L = { (0, -2t, t, u, v) : t, u, v in Z/8 },      |L mod 8| = 512.

The single statement is then `x0_ab not in M(L)`, one membership test per point.  Section 1
runs it exhaustively at all three points.  Section 2 asks whether any SINGLE column and single
modulus certifies it at all three - the question the three routes leave open - and section 3
drops the `nu'` half to see where it is load-bearing.

Run: `python3 scripts/w64_verify/task_c_legality.py`

BRACKET CONVENTION.  [NONE]
This script computes no commutators, so the convention does not arise.
Paper convention: commP x y = x^-1 y^-1 x y (GQ2/Words.lean:59, and every python commP
in scripts/).  Mathlib convention: [x, y] = x y x^-1 y^-1.  They are DIFFERENT families,
[x, y]_mathlib = commP x^-1 y^-1 (GradedFiveForce.commutatorElement_eq_commP), so a
paper-convention computation certifies a commP-written Lean statement and MIS-certifies a
[.,.]-written one.  Normal-closure and subgroup sifts are convention-IMMUNE.
"""
import itertools
import os

OUT = []
FAIL = [0]
CHECK = [0]


def check(name, cond, detail=""):
    CHECK[0] += 1
    if not cond:
        FAIL[0] += 1
    OUT.append("  [%s] %-66s %s" % ("ok " if cond else "FAIL", name, detail))


def say(s=""):
    OUT.append(s)


AB = "abcde"

# the five letters of each point, abelian columns only (a, b, c, d, e), in the slot order
# (sigma, x0, x1, u_j, v_j).  Transcribed from the Lean definitions, values only.
POINTS = {
    "w60  fiveFrameHom": {
        "sigma": (0, 1, 0, 0, 0),          # fiveSigMark = E_23
        "x0": (2, 0, 0, 0, 1),             # forceX  = <a=2, e=1>
        "x1": (0, 0, 0, 0, 2),             # forceY  = <e=2, ...>
        "U": (1, 0, 2, 3, 0),              # forceU  = <a=1, c=2, d=3, ...>
        "V": (0, 0, 0, 1, 2),              # forceV  = <d=1, e=2, ...>
    },
    "w61  stageFrameHom": {
        "sigma": (0, 1, 0, 0, 0),          # fiveSigMark = E_23
        "x0": (2, 0, 0, 0, 5),             # stageX  = <a=2, e=5>
        "x1": (0, 0, 0, 0, 2),             # stageY  = <e=2, ...>
        "U": (6, 7, 4, 1, 3),              # stageU
        "V": (6, 7, 6, 1, 3),              # stageV
    },
    "w63  liveBlkHom": {
        "sigma": (0, 1, 0, 1, 0),          # liveBlkSig = E_23 E_45
        "x0": (2, 0, 0, 0, 5),             # stageX, unchanged
        "x1": (0, 0, 0, 0, 2),             # liveBlkY = <e=2, ...>
        "U": (0, 0, 2, 1, 0),              # liveBlkU = <c=2, d=1>
        "V": (0, 0, 2, 0, 3),              # liveBlkV = <c=2, e=3, j=5>
    },
}

SLOTS = ["sigma", "x0", "x1", "U", "V"]


def image(pt, exps):
    """The abelian part of `Phi g` at exponent vector `exps`, a 5-tuple over Z/8."""
    return tuple(sum(exps[k] * pt[SLOTS[k]][c] for k in range(5)) % 8 for c in range(5))


def legal_exponents(with_nu=True):
    """`L`: lambda-trivial and (optionally) nu'-trivial exponent vectors, mod 8."""
    out = []
    for t, u, v in itertools.product(range(8), repeat=3):
        out.append((0, (-2 * t) % 8, t, u, v))
    if with_nu:
        return out
    # without the nu' half only `lambda g = c a_s + a_0 + 2 a_1 = 0` survives; c is a unit, so
    # a_s is determined by `a_0 + 2 a_1` up to the unit and ranges over everything as they do.
    out = []
    for c in [1, 3, 5, 7]:                       # sqPivotExp is a unit, value not committed
        for a0, a1, u, v in itertools.product(range(8), repeat=4):
            asx = (-pow(c, -1, 8) * (a0 + 2 * a1)) % 8
            out.append((asx, a0, a1, u, v))
    return out


say("=" * 100)
say("W64-VERIFY  task C: one statement for the ArbFrames legality question?")
say("=" * 100)
say()
say("1  THE UNIFORM CRITERION:  is  x0_ab  in  M(L) ?   (L is the SAME lattice at all three)")
say()
L = legal_exponents(True)
say("   |L mod 8| = %d" % len(L))
IMAGES = {}
for nm, pt in POINTS.items():
    W = {image(pt, e) for e in L}
    IMAGES[nm] = W
    tgt = pt["x0"]
    check("%s: x0_ab = %s is NOT reachable by any legal dressing" % (nm, tgt),
          tgt not in W, "|M(L)| = %d" % len(W))
say()
say("   => ONE statement, three instances, no per-point column argument needed:")
say("      `legality pins the exponents to L; the point's abelian matrix maps L to M(L);")
say("       the x0 slot is outside M(L)'.  Verified exhaustively over all 512 legal vectors.")

# ---- 2 is any SINGLE column enough at all three? ------------------------------------------

say()
say("2  THE CERTIFIED NEGATIVE: no single abelian column, at any modulus, works at all three")
say()
say("   column  modulus   w60      w61      w63     works everywhere?")
anywhere = []
for ci, c in enumerate(AB):
    for mod in [2, 4, 8]:
        oks = []
        for nm, pt in POINTS.items():
            vals = {w[ci] % mod for w in IMAGES[nm]}
            oks.append(pt["x0"][ci] % mod not in vals)
        say("      %s      %d      %-8s %-8s %-8s %s"
            % (c, mod, oks[0], oks[1], oks[2], "YES" if all(oks) else "no"))
        if all(oks):
            anywhere.append((c, mod))
check("NO single abelian column with a single modulus closes the door at all three points",
      not anywhere, "survivors: %s" % (anywhere if anywhere else "none"))
say()
say("   The three routes' own columns, and where each one dies:")
for ci, c, label in [(4, "e", "w60/w61 read the FIFTH column"),
                     (0, "a", "w63-live5 reads the FIRST column")]:
    for nm, pt in POINTS.items():
        vals = {w[ci] % 8 for w in IMAGES[nm]}
        reach = pt["x0"][ci] % 8 in vals
        say("      %-28s at %-20s x0.%s = %d, reachable: %s"
            % (label, nm, c, pt["x0"][ci], reach))

# ---- 3 is the nu' half load-bearing? ------------------------------------------------------

say()
say("3  Dropping the `nu'` half (lambda-triviality alone, a_s free)")
say()
L2 = legal_exponents(False)
for nm, pt in POINTS.items():
    W2 = {image(pt, e) for e in L2}
    reach = pt["x0"] in W2
    say("      %-22s x0 reachable on lambda alone: %-6s (|M(L)| = %d)" % (nm, reach, len(W2)))
    check("%s: whether nu'-triviality is load-bearing is decided" % nm, True,
          "load-bearing" if reach else "NOT load-bearing (lambda alone suffices)")

say()
say("=" * 100)
say("%d named checks, %d failures" % (CHECK[0], FAIL[0]))
say("=" * 100)

text = "\n".join(OUT) + "\n"
HERE = os.path.dirname(os.path.abspath(__file__))
os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
with open(os.path.join(HERE, "results", "task_c_legality.txt"), "w") as f:
    f.write(text)
print(text)
